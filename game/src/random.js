// Deterministic seeded random. Same seed, same sequence, same screenshots.
// A tiny linear congruential generator, no library, no Math.random anywhere.
export function makeRng(seed) {
  let s = (seed >>> 0) || 1;
  function next() {
    s = (s * 1664525 + 1013904223) >>> 0;
    return s / 4294967296;
  }
  return {
    float(min, max) {
      return min + next() * (max - min);
    },
    int(min, max) {
      return Math.floor(min + next() * (max - min + 1));
    },
    pick(list) {
      return list[Math.floor(next() * list.length)];
    },
    shuffle(list) {
      const out = list.slice();
      for (let i = out.length - 1; i > 0; i--) {
        const j = Math.floor(next() * (i + 1));
        const t = out[i];
        out[i] = out[j];
        out[j] = t;
      }
      return out;
    },
    chance(p) {
      return next() < p;
    },
    dice(sides) {
      return 1 + Math.floor(next() * sides);
    },
  };
}
